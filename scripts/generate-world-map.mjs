import { readFileSync, writeFileSync } from "node:fs";
import { geoPath, geoEquirectangular } from "d3-geo";
import { feature } from "topojson-client";

const WIDTH = 1000;
const HEIGHT = 500;

const topology = JSON.parse(
  readFileSync(new URL("../public/land-110m.json", import.meta.url), "utf8")
);

const projection = geoEquirectangular().fitSize([WIDTH, HEIGHT], { type: "Sphere" });
const pathGen = geoPath(projection);

const land = feature(topology, topology.objects.land);
const landPath = pathGen(land);

const samplePoints = [
  ["cusat", 76.3, 10.0],
  ["sf", -122.4, 37.8],
  ["nyc", -74.0, 40.7],
  ["london", -0.1, 51.5],
  ["berlin", 13.4, 52.5],
  ["dubai", 55.3, 25.2],
  ["singapore", 103.8, 1.3],
  ["tokyo", 139.7, 35.7],
  ["sydney", 151.2, -33.9],
  ["saopaulo", -46.6, -23.5],
];

const hubs = samplePoints.map(([id, lon, lat]) => {
  const pt = projection([Number(lon), Number(lat)]);
  return { id, lon: Number(lon), lat: Number(lat), x: pt?.[0] ?? 0, y: pt?.[1] ?? 0 };
});

const out = `/** Auto-generated by scripts/generate-world-map.mjs — do not edit */
export const WORLD_MAP_WIDTH = ${WIDTH};
export const WORLD_MAP_HEIGHT = ${HEIGHT};
export const WORLD_LAND_PATH = ${JSON.stringify(landPath)};
export const WORLD_MAP_HUBS = ${JSON.stringify(hubs)} as const;
`;

writeFileSync(new URL("../src/components/home/worldLandPath.ts", import.meta.url), out);
console.log(`Generated land path (${(landPath.length / 1024).toFixed(1)} KB)`);
